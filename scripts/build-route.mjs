// Builds a compact rover route for the mission page from NASA's corrected traverse table.
//
//   node scripts/build-route.mjs <traverse.csv> <output.ts> <exportName> [odometerKm]
//
//   node scripts/build-route.mjs MERB_traverse_5130.csv app/museum/routes/opportunity.ts opportunityRoute
//   node scripts/build-route.mjs MERA_traverse.csv app/museum/routes/spirit.ts spiritRoute 7.73
//
// Source: MER traverses by Tim Parker, corrected and interpolated by the PDS Geosciences Node.
// https://an.rsl.wustl.edu/mera/AN/pages/mer/mer_traverse.htm
// Positions are written as metres east and north of the landing point. The Spirit
// table uses absolute map coordinates, so the first row is subtracted as the origin.
//
// The table holds the end point of every drive, so the length of the line is a little
// shorter than the wheel odometer. Pass the official odometer reading as the last
// argument to show both numbers.
import fs from 'node:fs';

const [, , input, output, exportName, odometer] = process.argv;
if (!input || !output || !exportName) {
  console.error('Usage: node scripts/build-route.mjs <traverse.csv> <output.ts> <exportName> [odometerKm]');
  process.exit(1);
}

const rows = fs.readFileSync(input, 'utf8').trim().split(/\r?\n/).slice(1);
const parsed = [];
for (const line of rows) {
  const cells = line.split(',');
  const x = Number(cells[7]);
  const y = Number(cells[8]);
  if (!Number.isFinite(x) || !Number.isFinite(y)) continue;
  parsed.push({ x, y, sol: Number(cells[3]) });
}

const origin = parsed[0];
const full = [];
let travelled = 0;
for (const point of parsed) {
  const x = point.x - origin.x;
  const y = point.y - origin.y;
  const previous = full.at(-1);
  if (previous) travelled += Math.hypot(x - previous.x, y - previous.y);
  full.push({ x, y, sol: point.sol, km: travelled / 1000 });
}

// Ramer–Douglas–Peucker, iterative so 20k points cannot overflow the stack.
function simplify(points, tolerance) {
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let worst = 0;
    let index = -1;
    const { x: ax, y: ay } = points[a];
    const { x: bx, y: by } = points[b];
    const length = Math.hypot(bx - ax, by - ay) || 1;
    for (let i = a + 1; i < b; i += 1) {
      const distance = Math.abs((by - ay) * points[i].x - (bx - ax) * points[i].y + bx * ay - by * ax) / length;
      if (distance > worst) { worst = distance; index = i; }
    }
    if (worst > tolerance) {
      keep[index] = 1;
      stack.push([a, index], [index, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

// 18 m for a 23 km route; shorter routes get a finer tolerance so curves stay smooth.
const extent = Math.max(
  Math.max(...full.map((p) => p.x)) - Math.min(...full.map((p) => p.x)),
  Math.max(...full.map((p) => p.y)) - Math.min(...full.map((p) => p.y)),
);
const points = simplify(full, Math.min(18, extent * 0.002));
const round = (value, digits) => Number(value.toFixed(digits));
const last = full.at(-1);

const body = `// Generated by scripts/build-route.mjs. Do not edit by hand.
// Source: NASA/PDS corrected traverse (Tim Parker; PDS Geosciences Node).
// Each point is [metres east, metres north, sol, kilometres driven so far].
export const ${exportName} = {
  totalKm: ${round(last.km, 2)},${odometer ? `\n  odometerKm: ${Number(odometer)},` : ''}
  lastSol: ${last.sol},
  points: [${points.map((p) => `[${Math.round(p.x)},${Math.round(p.y)},${p.sol},${round(p.km, 2)}]`).join(',')}] as [number, number, number, number][],
};
`;
fs.writeFileSync(output, body);
console.log(`${full.length} rows -> ${points.length} points, ${round(last.km, 2)} km, last sol ${last.sol}`);
