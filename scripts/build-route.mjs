// Builds a compact rover route for the mission page from NASA's corrected traverse table.
//
//   node scripts/build-route.mjs <MERB_traverse_5130.csv> app/museum/routes/opportunity.ts
//
// Source: Opportunity traverse by Tim Parker, corrected and interpolated by the
// PDS Geosciences Node. https://an.rsl.wustl.edu/mera/AN/pages/mer/mer_traverse.htm
// Positions are metres east and north of the landing point.
import fs from 'node:fs';

const [, , input, output] = process.argv;
if (!input || !output) {
  console.error('Usage: node scripts/build-route.mjs <traverse.csv> <output.ts>');
  process.exit(1);
}

const TOLERANCE_M = 18;

const rows = fs.readFileSync(input, 'utf8').trim().split(/\r?\n/).slice(1);
const full = [];
let travelled = 0;
for (const line of rows) {
  const cells = line.split(',');
  const x = Number(cells[7]);
  const y = Number(cells[8]);
  if (!Number.isFinite(x) || !Number.isFinite(y)) continue;
  const previous = full.at(-1);
  if (previous) travelled += Math.hypot(x - previous.x, y - previous.y);
  full.push({ x, y, sol: Number(cells[3]), km: travelled / 1000 });
}

// Ramer–Douglas–Peucker, iterative so 20k points cannot overflow the stack.
function simplify(points, tolerance) {
  const keep = new Uint8Array(points.length);
  keep[0] = keep[points.length - 1] = 1;
  const stack = [[0, points.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    let worst = 0;
    let index = -1;
    const { x: ax, y: ay } = points[a];
    const { x: bx, y: by } = points[b];
    const length = Math.hypot(bx - ax, by - ay) || 1;
    for (let i = a + 1; i < b; i += 1) {
      const distance = Math.abs((by - ay) * points[i].x - (bx - ax) * points[i].y + bx * ay - by * ax) / length;
      if (distance > worst) { worst = distance; index = i; }
    }
    if (worst > tolerance) {
      keep[index] = 1;
      stack.push([a, index], [index, b]);
    }
  }
  return points.filter((_, i) => keep[i]);
}

const points = simplify(full, TOLERANCE_M);
const round = (value, digits) => Number(value.toFixed(digits));
const last = full.at(-1);

const body = `// Generated by scripts/build-route.mjs. Do not edit by hand.
// Source: NASA/PDS corrected traverse for Opportunity (Tim Parker; PDS Geosciences Node).
// Each point is [metres east, metres north, sol, kilometres driven so far].
export const opportunityRoute = {
  totalKm: ${round(last.km, 2)},
  lastSol: ${last.sol},
  points: [${points.map((p) => `[${Math.round(p.x)},${Math.round(p.y)},${p.sol},${round(p.km, 2)}]`).join(',')}] as [number, number, number, number][],
};
`;
fs.writeFileSync(output, body);
console.log(`${full.length} rows -> ${points.length} points, ${round(last.km, 2)} km, last sol ${last.sol}`);
